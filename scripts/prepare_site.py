#!/usr/bin/env python3
"""Prepare the static GitHub Pages output directory from RenderCV artifacts."""

from pathlib import Path
import re
import shutil

OUTPUT_DIR = Path("rendercv_output")
PUBLIC_DIR = Path("public")
HTML_SOURCE = OUTPUT_DIR / "Marine_Morard_CV.html"
PDF_SOURCE = OUTPUT_DIR / "Marine_Morard_CV.pdf"
PDF_TARGET_NAME = "Marine_Morard_CV.pdf"

BANNER_CSS = """
        .cv-download-bar {
            display: flex;
            align-items: center;
            justify-content: space-between;
            gap: 12px;
            flex-wrap: wrap;
            margin-bottom: 24px;
            padding: 10px 14px;
            border: 1px solid #d0d7de;
            border-radius: 6px;
            background-color: #f6f8fa;
            font-size: 14px;
            color: #57606a;
        }

        .cv-download-btn {
            display: inline-flex;
            align-items: center;
            gap: 6px;
            padding: 6px 14px;
            border-radius: 6px;
            background-color: #004f90;
            color: #ffffff !important;
            text-decoration: none !important;
            font-weight: 600;
            font-size: 13px;
            transition: background-color 0.15s ease;
        }

        .cv-download-btn:hover {
            background-color: #003a6b;
        }

        @media print {
            .cv-download-bar {
                display: none;
            }
        }
"""

BANNER_HTML = f"""
        <div class="cv-download-bar">
            <span>CV — Version web (généré automatiquement via RenderCV)</span>
            <a class="cv-download-btn" href="./{PDF_TARGET_NAME}" download="{PDF_TARGET_NAME}">
                ↓ Télécharger le PDF
            </a>
        </div>
"""


def main() -> None:
    if not HTML_SOURCE.exists():
        raise FileNotFoundError(f"Missing generated HTML: {HTML_SOURCE}")
    if not PDF_SOURCE.exists():
        raise FileNotFoundError(f"Missing generated PDF: {PDF_SOURCE}")

    if PUBLIC_DIR.exists():
        shutil.rmtree(PUBLIC_DIR)
    PUBLIC_DIR.mkdir(parents=True, exist_ok=True)

    html = HTML_SOURCE.read_text(encoding="utf-8")

    # Populate empty <title> generated by RenderCV
    html = re.sub(
        r"<title>\s*</title>",
        "<title>Marine MORARD — CV</title>",
        html,
        count=1,
    )

    # Localize default RenderCV Markdown heading if present
    html = html.replace("<h1>Marine MORARD's CV</h1>", "<h1>Marine MORARD</h1>", 1)

    # Inject banner CSS cleanly before </style>
    if "</style>" in html:
        html = html.replace("</style>", f"{BANNER_CSS}    </style>", 1)
    else:
        html = html.replace("</head>", f"<style>{BANNER_CSS}</style>\n</head>", 1)

    # Inject discrete PDF download bar at the top of the article
    article_marker = '<article class="markdown-body">'
    if article_marker in html:
        html = html.replace(article_marker, f"{article_marker}{BANNER_HTML}", 1)
    else:
        html = html.replace("<body>", f"<body>{BANNER_HTML}", 1)

    (PUBLIC_DIR / "index.html").write_text(html, encoding="utf-8")
    shutil.copy2(PDF_SOURCE, PUBLIC_DIR / PDF_TARGET_NAME)
    (PUBLIC_DIR / ".nojekyll").write_text("", encoding="utf-8")

    print(f"Prepared {PUBLIC_DIR}/index.html and {PUBLIC_DIR}/{PDF_TARGET_NAME}")


if __name__ == "__main__":
    main()
